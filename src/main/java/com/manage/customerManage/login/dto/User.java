package com.manage.customerManage.login.dto;

public class User {
    private Long id;
    private String userId;
    private String password;
    private String name;


    public Long getId() {
        return id;
    }

    public String getUserId() {
        return userId;
    }

    public String getPassword() {
        return password;
    }

    public String getName() {
        return name;
    }
}
